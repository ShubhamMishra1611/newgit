"""
Sanity check S2: the Veneziano amplitude.

A(s,t) = Gamma(-a(s)) Gamma(-a(t)) / Gamma(-a(s)-a(t)),   a(x) = 1 + x   (alpha' = 1)
External open-string tachyons, m^2 = -1, s + t + u = -4.
Reference (ESTABLISHED): Veneziano, Nuovo Cim. A57 (1968) 190 [pre-arXiv];
Polchinski Vol. 1 eq. (6.4.10)-(6.4.13) region (Veneziano amplitude & its poles);
Green-Schwarz-Witten Vol. 1 Ch. 1.

Checks:
  (a) poles at a(s) = n = 0,1,2,... with residue R_n(t) = (a(t)+1)_n / n!, a
      polynomial of degree n in t (spins <= n), symbolic.
  (b) s<->t symmetry, and "duality": the sum over s-channel poles alone
      reproduces the full amplitude (incl. its t-channel poles) where the
      series converges (Re a(t) < 0), numerically.
  (c) Regge limit: A ~ Gamma(-a(t)) (-a(s))^{a(t)} at large |s|, fixed t.
  (d) Partial-wave (Gegenbauer) decomposition of R_n in D dimensions: the
      largest D for which all coefficients are >= 0 at levels n <= N.
      (unitarity of the tree amplitude; Ref. to compare: Arkani-Hamed,
      Eberhardt, Huang, Mizera, arXiv:2201.11575 -- checked separately.)
  (e) the low-energy expansion coefficients of the massless-pole-subtracted
      amplitude (zeta values).
"""
import sympy as sp
import mpmath as mp

out = []
def log(*a):
    s = " ".join(str(x) for x in a)
    print(s)
    out.append(s)

s, t, x = sp.symbols('s t x')
al = lambda v: 1 + v

def A_num(sv, tv):
    return mp.gamma(-al(sv)) * mp.gamma(-al(tv)) / mp.gamma(-al(sv) - al(tv))

# (a) residues
log("=== (a) s-channel poles and residues ===")
for n in range(0, 6):
    # residue of A in the variable (n - a(s)) i.e. A ~ R_n(t)/(n - a(s))
    eps = sp.symbols('epsilon')
    # a(s) = n - eps  =>  A * (n - a(s)) = eps*A ; take eps -> 0
    expr = sp.gamma(-(n - eps)) * sp.gamma(-al(t)) / sp.gamma(-(n - eps) - al(t)) * eps
    R = sp.simplify(sp.gammasimp(sp.limit(sp.gammasimp(expr), eps, 0)))
    R_expected = sp.rf(al(t) + 1, n) / sp.factorial(n)
    ok = sp.simplify(sp.expand_func(R - R_expected)) == 0
    log(f"  n={n}: m^2 = {n-1}, residue R_n(t) = {sp.factor(sp.expand_func(R))},  "
        f"deg_t = {sp.degree(sp.expand(sp.expand_func(R)), t)},  matches (a(t)+1)_n/n!: {ok}")

# (b) symmetry and duality
log("\n=== (b) s-t symmetry and pole-sum duality (numerical) ===")
mp.mp.dps = 30
for (sv, tv) in [(-1.3 + 0.7j, -2.6), (0.4 + 0.2j, -3.2), (2.5 + 0.1j, -2.3)]:
    sym = abs(A_num(sv, tv) - A_num(tv, sv))
    # pole sum: sum_n R_n(t)/(n - a(s)); converges for Re a(t) < 0.
    # R_n written analytically in n so Euler-Maclaurin tail summation applies.
    term = lambda n, tv=tv, sv=sv: mp.gamma(al(tv) + 1 + n) / (mp.gamma(al(tv) + 1) * mp.gamma(n + 1)) / (n - al(sv))
    S = mp.nsum(term, [0, mp.inf], method='euler-maclaurin')
    log(f"  s={sv}, t={tv} (a(t)={al(tv):.2f}): |A(s,t)-A(t,s)| = {mp.nstr(sym,3)};  "
        f"A = {mp.nstr(A_num(sv,tv),15)},  sum_n R_n/(n-a(s)) = {mp.nstr(S,15)}")
# t-channel pole seen by the s-channel sum: approach a(t) -> 0 from below
log("  t-channel pole emerging from the s-channel sum: (-a(t)) * sum_n R_n(t)/(n-a(s)) as a(t) -> 0^-")
log("  (expected -> R_0 = 1, the t-channel tachyon residue; no individual s-channel term has this pole)")
sv = -1.7
for d in (mp.mpf('1e-1'), mp.mpf('1e-2'), mp.mpf('1e-3'), mp.mpf('1e-4')):
    tv = -1 - d          # a(t) = -d
    a_t = al(tv)
    # term(n) ~ n^(a_t - 1)/Gamma(a_t + 1): subtract it, sum the remainder, add zeta(1 - a_t)/Gamma(a_t+1)
    term = lambda n, a_t=a_t: mp.gamma(a_t + 1 + n) / (mp.gamma(a_t + 1) * mp.gamma(n + 1)) / (n - al(sv))
    sub = lambda n, a_t=a_t: term(n) - n ** (a_t - 1) / mp.gamma(a_t + 1)
    S = term(0) + mp.nsum(sub, [1, mp.inf]) + mp.zeta(1 - a_t) / mp.gamma(a_t + 1)
    log(f"    a(t) = {mp.nstr(-d,3)}:  (-a(t)) * [s-channel pole sum] = {mp.nstr(d*S, 12)},  (-a(t))*A(s,t) = {mp.nstr(d*A_num(sv,tv),12)}")
log("  => the t-channel pole is generated by the large-n tail of the s-channel tower (zeta(1+d) ~ 1/d).")
log("  analytic statement: sum_n (a_t+1)_n/(n!(n-a_s)) = (1/(-a_s)) 2F1(a_t+1,-a_s;1-a_s;1) = Gamma(-a_s)Gamma(-a_t)/Gamma(-a_s-a_t) by Gauss's theorem.")

# (c) Regge
log("\n=== (c) Regge limit ===")
for tv in (-1.5, -0.5, 0.3):
    for R_ in (1e2, 1e4, 1e6):
        sv = R_ * mp.exp(0.75j * mp.pi)      # away from the real axis where the poles sit
        exact = A_num(sv, tv)
        regge = mp.gamma(-al(tv)) * (-al(sv)) ** al(tv)
        log(f"  t={tv}, |s|={R_:.0e} (arg s = 3pi/4): |A/Regge - 1| = {mp.nstr(abs(exact/regge - 1), 4)}")
log("  (corrections fall like 1/|s|; along the real s axis the limit holds only on average because of the poles)")

# (d) partial waves
log("\n=== (d) Gegenbauer partial waves of residues, unitarity vs dimension D ===")
Dsym = sp.symbols('D')
def pw_coeffs(n, Dval):
    """R_n(t(x)) = sum_j c_j C_j^{(D-3)/2}(x).  s = n-1, t = -(s+4)/2 (1-x)."""
    sv = n - 1
    tv = -sp.Rational(sv + 4, 2) * (1 - x)
    R = sp.expand(sp.rf(al(tv) + 1, n) / sp.factorial(n))
    lam = sp.Rational(Dval - 3, 2)
    coeffs = []
    rem = sp.Poly(R, x)
    cs = {}
    for j in range(n, -1, -1):
        Cj = sp.Poly(sp.gegenbauer(j, lam, x) if lam != 0 else sp.chebyshevt(j, x), x)
        lead = rem.coeff_monomial(x**j)
        cj = lead / Cj.coeff_monomial(x**j)
        cs[j] = sp.nsimplify(cj)
        rem = rem - Cj * cj
    assert rem.is_zero or all(abs(cc) < 1e-20 for cc in rem.all_coeffs())
    return cs

Nmax = 12
for Dval in (4, 10, 26, 27, 28):
    neg = []
    for n in range(1, Nmax + 1):
        cs = pw_coeffs(n, Dval)
        for j, cj in cs.items():
            if cj < 0:
                neg.append((n, j, float(cj)))
    log(f"  D={Dval}: negative partial-wave coefficients at levels n<= {Nmax}: "
        f"{neg[:6] if neg else 'none'}{' ...' if len(neg) > 6 else ''}")
# exact: Gegenbauer coefficients as rational functions of D
log("  exact c_j(D) at low levels (symbolic D), and the largest D with all c_j >= 0:")
def pw_coeffs_sym(n):
    sv = n - 1
    tv = -sp.Rational(sv + 4, 2) * (1 - x)
    R = sp.Poly(sp.expand(sp.rf(al(tv) + 1, n) / sp.factorial(n)), x)
    lam = (Dsym - 3) / 2
    rem = R
    cs = {}
    for j in range(n, -1, -1):
        Cj = sp.Poly(sp.expand(sp.gegenbauer(j, lam, x)), x)
        cj = sp.factor(sp.cancel(rem.coeff_monomial(x**j) / Cj.coeff_monomial(x**j)))
        cs[j] = cj
        rem = sp.Poly(sp.expand(rem.as_expr() - Cj.as_expr() * cj), x)
        rem = sp.Poly(sp.cancel(rem.as_expr()), x)
    assert sp.simplify(rem.as_expr()) == 0
    return cs
crit_overall = sp.oo
for n in range(1, 9):
    cs = pw_coeffs_sym(n)
    crit_n = sp.oo
    for j, cj in cs.items():
        num, den = sp.fraction(sp.together(cj))
        roots = [r for r in sp.Poly(num, Dsym).real_roots() if r > 4] if sp.Poly(num, Dsym).degree() > 0 else []
        for r in roots:
            # check sign change just above root
            if cj.subs(Dsym, r + sp.Rational(1, 10**6)) < 0:
                crit_n = min(crit_n, r)
        if n <= 3:
            log(f"    n={n}, j={j}: c_j(D) = {cj}")
    crit_overall = min(crit_overall, crit_n)
    log(f"    level n={n}: all c_j(D) >= 0 for 4 <= D <= {crit_n if crit_n != sp.oo else 'infinity (no bound)'}"
        f"{'  (approx ' + str(sp.N(crit_n, 8)) + ')' if crit_n not in (sp.oo,) and not crit_n.is_Integer else ''}")
log(f"  => tightest bound from levels 1..8: D <= {crit_overall}")

# (e) low-energy expansion
log("\n=== (e) low-energy expansion ===")
# Gamma(1-a)Gamma(1-b)/Gamma(1-a-b) = exp( sum_{k>=2} zeta(k)/k (a^k + b^k - (a+b)^k) )
a_, b_ = sp.symbols('a b')
expo = sum(sp.zeta(k) / k * (a_**k + b_**k - (a_ + b_)**k) for k in range(2, 6))
ser = sp.series(sp.exp(expo), a_, 0, 5).removeO()
ser = sp.expand(sp.series(ser, b_, 0, 5).removeO())
poly = sum(term for term in sp.Add.make_args(ser) if sp.Poly(term, a_, b_).total_degree() <= 4)
log(f"  Gamma(1-a)Gamma(1-b)/Gamma(1-a-b) = 1 + {sp.simplify(poly - 1)} + O(5)")
mp.mp.dps = 25
av, bv = mp.mpf('0.013'), mp.mpf('-0.021')
lhs = mp.gamma(1-av)*mp.gamma(1-bv)/mp.gamma(1-av-bv)
rhs = sp.N(poly.subs({a_: sp.Float('0.013', 25), b_: sp.Float('-0.021', 25)}), 25)
log(f"  numeric check at a=0.013, b=-0.021: exact = {mp.nstr(lhs, 18)}, series = {rhs}")
log("  (A(s,t) = -(a+b)/(a b) * Gamma(1-a)Gamma(1-b)/Gamma(1-a-b) with a=a(s), b=a(t):")
log("   leading coefficient of a*b is -zeta(2): first stringy correction ~ zeta(2) alpha'^2.)")

with open(__file__.replace('.py', '_output.txt'), 'w') as f:
    f.write("\n".join(out) + "\n")
